// Lines the memoji can make up on the spot. Two sources:
//   - Chrome's built-in model (Gemini Nano, via the Prompt API), used only when
//     the model is already on the visitor's device: availability() must say
//     "available", so a visit never starts a model download.
//   - Otherwise jonyen.com/quip, a Worker that asks a small open model on
//     Cloudflare Workers AI (see quip/ in this repo), so iPhone, Safari and
//     Firefox visitors get made-up lines too.
// Each line carries a credit saying what wrote it. Anything that fails or is
// slow falls back to the fixed sayings.

export const MODEL_CREDIT = 'Generated by Gemini Nano in Chrome, on your device';

const QUIP_URL = '/quip';
const QUIP_TIMEOUT_MS = 4000;
// After this many failed /quip calls in one page view, stop asking.
const QUIP_MAX_FAILURES = 3;

// "Generated by Gemma 4 on Cloudflare Workers AI".
export const quipCredit = ({ modelName }) => `Generated by ${modelName} on Cloudflare Workers AI`;

const LM_OPTIONS = {
  expectedInputs: [{ type: 'text', languages: ['en'] }],
  expectedOutputs: [{ type: 'text', languages: ['en'] }],
};

// Same rules as the Workers AI prompt in quip/src/handler.js.
const SYSTEM_PROMPT = [
  'You write one witty line for the speech bubble of a cartoon avatar on the personal website of',
  'Jonathan Yen, a full stack engineer. Speak as Jonathan, in the first person. Make it genuinely',
  'funny: general wit, an everyday observation, a pun or engineering humour. Light, clean humour.',
  'Don\'t reference faith, prayer, church or God unless it is a genuinely clever programming pun,',
  'and keep that rare. Never mention employers or companies he has worked for, politics, or',
  'anything edgy. No jokes about Washington DC, its traffic, the Metro or the weather.',
  'Don\'t say you are away, offline, resting or recharging. Don\'t start with "I have", "I\'m",',
  '"I am", "I\'m currently" or "I once"; vary the form: questions, observations, one-line',
  'stories, pun setups, imperatives. At most 20 words. Reply with the line only: no quotes, no',
  'emoji, no hashtags, no links, no markdown.',
].join(' ');

// One opening style is picked at random per line, so the lines don't all
// start the same way.
const OPENINGS = [
  'Open with a question.',
  'Make it an everyday observation that starts with "Nothing".',
  'Tell a one-line story that starts with "Today".',
  'Set up a pun and land it.',
  'Start with an imperative, like a tip or a warning.',
  'Start with "Fun fact:".',
  'Start with "Pro tip:".',
  'Write it as a definition: "X: the ...".',
  'Start with "My" and something Jonathan owns or does.',
  'Start with "Somewhere" or "Someday".',
];

// A line that opens like this gets one retry, then the fixed sayings.
const TIRED_OPENING = /^(i have a|i['’]m currently)\b/i;

// Employers and other names the line must never contain.
const BLOCKLIST = /datavault|dvlt|atlassian|mercor|medallia|\bibm\b|aspera|cvent|employer/i;
const MAX_CHARS = 140;


let session = null; // Promise of a LanguageModel session (or null), created once per page view.
let pending = null; // Promise of the next generated line.
let ready = null; // The next generated line, { text, credit }, once it has arrived.
let off = false; // Chrome's model isn't usable on this device; stop trying it.
let quipFailures = 0;
let quipOff = false; // /quip said no (rate limit, cap, missing); stop asking.
const recent = [];

async function modelAvailable() {
  if (!('LanguageModel' in window)) return false;
  try {
    return (await window.LanguageModel.availability(LM_OPTIONS)) === 'available';
  } catch {
    return false;
  }
}

// Start the session and fetch the first line in the background. Safe to call
// often; hover, focus and click all call it. create() may need a user gesture,
// so a refusal before the first click leaves room to try again on the click.
export function warmUp() {
  if (session) {
    prefetch();
    return;
  }
  session = (async () => {
    if (!(await modelAvailable())) {
      off = true;
      return null;
    }
    return window.LanguageModel.create({
      ...LM_OPTIONS,
      initialPrompts: [{ role: 'system', content: SYSTEM_PROMPT }],
    });
  })().catch((err) => {
    if (err?.name === 'NotAllowedError') session = null;
    else off = true;
    return null;
  });
  prefetch();
}

// The next generated line, { text, credit }, if one is waiting, else null.
// Taking it starts the next one, so the following click has a line ready too.
export function takeModelLine() {
  if (!ready) return null;
  const line = ready;
  ready = null;
  prefetch();
  return line;
}

function prefetch() {
  if (pending || ready || !session || (off && quipOff)) return;
  pending = generate()
    .then((line) => {
      if (line) {
        ready = line;
        recent.push(line.text);
        if (recent.length > 5) recent.shift();
      }
    })
    .catch(() => {})
    .finally(() => {
      pending = null;
    });
}

async function generate() {
  const base = await session;
  if (!base) return quipOff ? null : fetchQuip();
  // Each line comes from a fresh clone, so the conversation never grows.
  const once = async () => {
    const s = await base.clone();
    try {
      return clean(await s.prompt(promptText()));
    } finally {
      s.destroy();
    }
  };
  let text = await once();
  if (text && TIRED_OPENING.test(text)) text = await once();
  return text && !TIRED_OPENING.test(text) ? { text, credit: MODEL_CREDIT } : null;
}

// One line from the Workers AI Worker. A 429 (rate limit or daily cap) or a
// missing endpoint stops further calls for this page view; other failures are
// retried on later clicks, a few times at most.
async function fetchQuip() {
  const url = new URL(QUIP_URL, window.location.origin);
  for (const r of recent) url.searchParams.append('avoid', r);
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), QUIP_TIMEOUT_MS);
  try {
    const res = await fetch(url, { signal: controller.signal, credentials: 'omit' });
    if (res.status === 429 || res.status === 404) quipOff = true;
    if (res.status !== 200) throw new Error(`quip ${res.status}`);
    const data = await res.json();
    const text = clean(data.text);
    if (!text) throw new Error('quip filtered');
    return { text, credit: quipCredit(data) };
  } catch {
    quipFailures += 1;
    if (quipFailures >= QUIP_MAX_FAILURES) quipOff = true;
    return null;
  } finally {
    clearTimeout(timer);
  }
}

function promptText() {
  const now = new Date();
  const weekday = new Intl.DateTimeFormat('en-US', { weekday: 'long' }).format(now);
  const hour = now.getHours();
  const part = hour < 5 ? 'late night' : hour < 12 ? 'morning' : hour < 17 ? 'afternoon' : hour < 21 ? 'evening' : 'night';
  const lines = [`It is ${weekday} ${part} for the visitor.`];
  lines.push(`Style: ${OPENINGS[Math.floor(Math.random() * OPENINGS.length)]}`);
  if (recent.length) lines.push(`Don't repeat these: ${recent.join(' / ')}`);
  lines.push('Write one new line.');
  return lines.join('\n');
}

// Quotes, markdown and stray whitespace come off; anything too long, empty,
// link-like or on the blocklist is dropped so a fixed saying shows instead.
export function clean(raw) {
  if (typeof raw !== 'string') return null;
  let line = raw
    .replace(/[*_`#>~]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^["'“”‘’]+|["'“”‘’]+$/g, '')
    .trim();
  if (!line || line.length > MAX_CHARS) return null;
  if (/https?:|www\.|\]\(|\.(com|org|net)\b/i.test(line)) return null;
  if (BLOCKLIST.test(line)) return null;
  return line;
}
